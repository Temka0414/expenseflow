"""Every key format of ExpenseFlow - DynamoDB keys (SPEC section 3) and S3 object keys - spelled out in one place.

Single-table design stores several entity types in one table and models each access pattern as a key lookup::

    Expense            PK EXPENSE#{id}       SK META
                       GSI1 OWNER#{ownerId} / {createdAt}#{id}     -> "my expenses, newest first"
                       GSI2 STATUS#{status} / {updatedAt}#{id}     -> "approval queue", "approved in month M"
    History entry      PK EXPENSE#{id}       SK HISTORY#{at}#STATUS#{to} | HISTORY#{at}#RECEIPT
    Monthly total      PK USER#{ownerId}|ORG SK TOTAL#{yyyy-mm}#{currency}
    WebSocket audience PK WSCONN#{connId}    SK AUD#{audience}
                       GSI1 WSAUD#{audience} / {connId}           -> "connections to notify"

An expense and its history share a partition key, so one ``Query(PK = EXPENSE#{id})`` returns the whole
"item collection". Timestamps are ISO-8601 strings, so sort keys that start with them sort chronologically.
"""

from __future__ import annotations

from typing import Final

PK: Final = "PK"
SK: Final = "SK"
GSI1: Final = "GSI1"
GSI1PK: Final = "GSI1PK"
GSI1SK: Final = "GSI1SK"
GSI2: Final = "GSI2"
GSI2PK: Final = "GSI2PK"
GSI2SK: Final = "GSI2SK"
# Attributes that make up each index's keys. A page cursor (LastEvaluatedKey) of a GSI query contains the
# index keys *and* the table keys, because GSI keys alone need not be unique.
GSI1_KEY_ATTRIBUTES: Final = (PK, SK, GSI1PK, GSI1SK)
GSI2_KEY_ATTRIBUTES: Final = (PK, SK, GSI2PK, GSI2SK)

# Values of the `entityType` attribute: self-describing items make the table readable in the console.
ENTITY_EXPENSE: Final = "Expense"
ENTITY_HISTORY: Final = "History"
ENTITY_MONTHLY_TOTAL: Final = "MonthlyTotal"
ENTITY_WS_CONNECTION: Final = "WsConnection"

META: Final = "META"
ORG_PK: Final = "ORG"
EXPENSE_PREFIX: Final = "EXPENSE#"
HISTORY_PREFIX: Final = "HISTORY#"
TOTAL_PREFIX: Final = "TOTAL#"
SEPARATOR: Final = "#"

# --- Expense ----------------------------------------------------------------------------------------------


def expense_pk(expense_id: str) -> str:
    return f"{EXPENSE_PREFIX}{expense_id}"


def expense_key(expense_id: str) -> dict[str, str]:
    """Primary key of an expense's META item."""
    return {PK: expense_pk(expense_id), SK: META}


def owner_gsi1pk(owner_id: str) -> str:
    return f"OWNER#{owner_id}"


def owner_gsi1sk(created_at: str, expense_id: str) -> str:
    return f"{created_at}#{expense_id}"


def status_gsi2pk(status: str) -> str:
    return f"STATUS#{status}"


def status_gsi2sk(updated_at: str, expense_id: str) -> str:
    return f"{updated_at}#{expense_id}"


def status_gsi2sk_month_prefix(month: str) -> str:
    """``begins_with`` prefix selecting expenses whose status changed in ``month`` (``YYYY-MM``).

    The trailing ``-`` keeps the prefix unambiguous: ``2026-1`` must not match October-December.
    APPROVED is a terminal status, so for ``STATUS#APPROVED`` this selects the expenses approved that month.
    """
    return f"{month}-"


# --- History ----------------------------------------------------------------------------------------------


def history_sk_status(at: str, to_status: str) -> str:
    return f"{HISTORY_PREFIX}{at}#STATUS#{to_status}"


def history_sk_receipt(at: str) -> str:
    return f"{HISTORY_PREFIX}{at}#RECEIPT"


# --- Monthly totals ---------------------------------------------------------------------------------------


def user_total_pk(owner_id: str) -> str:
    return f"USER#{owner_id}"


def total_sk(month: str, currency: str) -> str:
    return f"{TOTAL_PREFIX}{month}#{currency}"


def total_sk_year_prefix(year: int) -> str:
    """``begins_with`` prefix selecting every monthly total of one year: ``TOTAL#2026-``."""
    return f"{TOTAL_PREFIX}{year:04d}-"


def parse_total_sk(sk: str) -> tuple[str, str]:
    """Split ``TOTAL#{yyyy-mm}#{currency}`` into ``(month, currency)``."""
    match sk.split(SEPARATOR):
        case [prefix, month, currency] if f"{prefix}{SEPARATOR}" == TOTAL_PREFIX and month and currency:
            return month, currency
        case _:
            raise ValueError(f"not a total sort key: {sk!r}")


# --- WebSocket connections --------------------------------------------------------------------------------


def audience_user(user_id: str) -> str:
    return f"USER#{user_id}"


def audience_group(group: str) -> str:
    return f"GROUP#{group}"


def wsconn_pk(connection_id: str) -> str:
    return f"WSCONN#{connection_id}"


def aud_sk(audience: str) -> str:
    return f"AUD#{audience}"


def wsaud_gsi1pk(audience: str) -> str:
    return f"WSAUD#{audience}"


# --- S3 object keys ---------------------------------------------------------------------------------------
# Keys are generated by the server from ULIDs and fixed extensions, so they only contain [A-Za-z0-9/_.-]:
# nothing needs URL-encoding, and the ReceiptPipeline can split them on "/" to recover owner and expense ids.

RECEIPTS_PREFIX: Final = "receipts/"
REPORTS_PREFIX: Final = "reports/"
REPORT_SUFFIX: Final = ".csv"


def receipt_prefix(owner_id: str, expense_id: str) -> str:
    """Folder holding every receipt object ever uploaded for one expense: ``receipts/{ownerId}/{expenseId}/``."""
    return f"{RECEIPTS_PREFIX}{owner_id}/{expense_id}/"


def receipt_object_key(owner_id: str, expense_id: str, object_id: str, extension: str) -> str:
    """``receipts/{ownerId}/{expenseId}/{objectId}{ext}``; a fresh ``object_id`` per upload avoids stale caches."""
    return f"{receipt_prefix(owner_id, expense_id)}{object_id}{extension}"


def report_object_key(month: str) -> str:
    """``reports/{yyyy-mm}.csv`` - regenerating a month overwrites its report."""
    return f"{REPORTS_PREFIX}{month}{REPORT_SUFFIX}"


def month_from_report_key(key: str) -> str | None:
    """Inverse of :func:`report_object_key`; ``None`` for keys that are not monthly reports."""
    if not (key.startswith(REPORTS_PREFIX) and key.endswith(REPORT_SUFFIX)):
        return None
    month = key.removeprefix(REPORTS_PREFIX).removesuffix(REPORT_SUFFIX)
    return month if "/" not in month else None
